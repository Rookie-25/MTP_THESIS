@triton.jit
def _fused_gbm_forward_kernel(
    dw_ptr,
    params_ptr,
    out_ptr,
    n_paths,
    n_steps,
    dw_stride_m,
    dw_stride_n,
    out_stride_m,
    out_stride_n,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
    DTYPE: tl.constexpr,
):
    """Fuse increment scaling, the time-axis scan, ``exp`` and the S0 scale.

    Each program owns ``BLOCK_M`` paths and walks the entire time axis in
    chunks of ``BLOCK_N``, carrying the running log-path offset between chunks.

    Args:
        dw_ptr: Brownian increments, shape ``(n_paths, n_steps)``.
        params_ptr: Packed ``[s0, mu, sigma, dt]`` in the working dtype. Passed
            as a device tensor rather than as Python floats so that float64
            precision survives -- scalar JIT arguments would be demoted to
            float32.
        out_ptr: Output paths, shape ``(n_paths, n_steps + 1)``.
        n_paths: Number of paths :math:`M`.
        n_steps: Number of time steps :math:`N`.
        dw_stride_m: Row stride of ``dw_ptr``.
        dw_stride_n: Column stride of ``dw_ptr``.
        out_stride_m: Row stride of ``out_ptr``.
        out_stride_n: Column stride of ``out_ptr``.
        BLOCK_M: Paths per program.
        BLOCK_N: Time steps per chunk (power of two).
        DTYPE: Working element type.
    """
    pid = tl.program_id(axis=0)
    offs_m = pid * BLOCK_M + tl.arange(0, BLOCK_M)
    mask_m = offs_m < n_paths

    s0 = tl.load(params_ptr + 0)
    mu = tl.load(params_ptr + 1)
    sigma = tl.load(params_ptr + 2)
    dt = tl.load(params_ptr + 3)

    # Ito-corrected drift per step.
    drift = (mu - 0.5 * sigma * sigma) * dt

    zeros_m = tl.zeros([BLOCK_M], dtype=DTYPE)
    zeros_mn = tl.zeros([BLOCK_M, BLOCK_N], dtype=DTYPE)

    # Column 0 is exactly S0 on every path (log-path offset zero).
    tl.store(out_ptr + offs_m * out_stride_m, s0 + zeros_m, mask=mask_m)

    carry = zeros_m
    for start in range(0, n_steps, BLOCK_N):
        offs_n = start + tl.arange(0, BLOCK_N)
        mask_n = offs_n < n_steps
        mask = mask_m[:, None] & mask_n[None, :]

        dw = tl.load(
            dw_ptr + offs_m[:, None] * dw_stride_m + offs_n[None, :] * dw_stride_n,
            mask=mask,
            other=0.0,
        )
        # The `where` is essential: padded lanes must contribute zero, but
        # `drift + sigma * 0` is `drift`, which would leak spurious drift into
        # both the scan and the carry.
        increments = tl.where(mask, drift + sigma * dw, zeros_mn)

        log_path = tl.cumsum(increments, axis=1) + carry[:, None]

        # Time index j lands in output column j + 1.
        tl.store(
            out_ptr
            + offs_m[:, None] * out_stride_m
            + (offs_n[None, :] + 1) * out_stride_n,
            s0 * tl.exp(log_path),
            mask=mask,
        )

        carry = carry + tl.sum(increments, axis=1)


@triton.jit
def _fused_gbm_backward_kernel(
    grad_out_ptr,
    out_ptr,
    dw_ptr,
    params_ptr,
    grad_dw_ptr,
    partial_s0_ptr,
    partial_mu_ptr,
    partial_sigma_ptr,
    n_paths,
    n_steps,
    go_stride_m,
    go_stride_n,
    out_stride_m,
    out_stride_n,
    dw_stride_m,
    dw_stride_n,
    gdw_stride_m,
    gdw_stride_n,
    BLOCK_M: tl.constexpr,
    BLOCK_N: tl.constexpr,
    DTYPE: tl.constexpr,
):
    """Hand-written adjoint of :func:`_fused_gbm_forward_kernel`.

    Walks time chunks in **reverse** to accumulate the suffix sum
    :math:`Q_{m,j} = \\sum_{k\\ge j} G_{m,k}S_{m,k}`, then contracts it against
    :math:`\\partial\\iota/\\partial\\theta` for each parameter. Scalar
    gradients are written as per-program partials and reduced host-side, which
    keeps the result bitwise reproducible.

    Args:
        grad_out_ptr: Incoming adjoint, shape ``(n_paths, n_steps + 1)``.
        out_ptr: Forward output :math:`S`, shape ``(n_paths, n_steps + 1)``.
        dw_ptr: Brownian increments, shape ``(n_paths, n_steps)``.
        params_ptr: Packed ``[s0, mu, sigma, dt]``.
        grad_dw_ptr: Output gradient w.r.t. ``dW``, shape ``(n_paths, n_steps)``.
        partial_s0_ptr: Per-program partial sums for ``dL/ds0``.
        partial_mu_ptr: Per-program partial sums for ``dL/dmu``.
        partial_sigma_ptr: Per-program partial sums for ``dL/dsigma``.
        n_paths: Number of paths :math:`M`.
        n_steps: Number of time steps :math:`N`.
        go_stride_m: Row stride of ``grad_out_ptr``.
        go_stride_n: Column stride of ``grad_out_ptr``.
        out_stride_m: Row stride of ``out_ptr``.
        out_stride_n: Column stride of ``out_ptr``.
        dw_stride_m: Row stride of ``dw_ptr``.
        dw_stride_n: Column stride of ``dw_ptr``.
        gdw_stride_m: Row stride of ``grad_dw_ptr``.
        gdw_stride_n: Column stride of ``grad_dw_ptr``.
        BLOCK_M: Paths per program.
        BLOCK_N: Time steps per chunk (power of two).
        DTYPE: Working element type.
    """
    pid = tl.program_id(axis=0)
    offs_m = pid * BLOCK_M + tl.arange(0, BLOCK_M)
    mask_m = offs_m < n_paths

    s0 = tl.load(params_ptr + 0)
    sigma = tl.load(params_ptr + 2)
    dt = tl.load(params_ptr + 3)

    zeros_m = tl.zeros([BLOCK_M], dtype=DTYPE)
    zeros_mn = tl.zeros([BLOCK_M, BLOCK_N], dtype=DTYPE)

    # Column 0 depends on S0 directly (dS/dS0 = 1) and on nothing else.
    grad_column_zero = tl.load(
        grad_out_ptr + offs_m * go_stride_m, mask=mask_m, other=0.0
    )
    acc_s0 = tl.where(mask_m, grad_column_zero, zeros_m)
    acc_mu = zeros_m
    acc_sigma = zeros_m

    # `carry` holds the suffix sum of P over every time index beyond the chunk
    # currently being processed.
    carry = zeros_m
    n_chunks = (n_steps + BLOCK_N - 1) // BLOCK_N

    for chunk in range(0, n_chunks):
        # Reverse traversal expressed with a forward loop: Triton's support for
        # negative-step ranges over runtime bounds is version-dependent.
        start = (n_chunks - 1 - chunk) * BLOCK_N
        offs_n = start + tl.arange(0, BLOCK_N)
        mask_n = offs_n < n_steps
        mask = mask_m[:, None] & mask_n[None, :]

        column_offsets = (offs_n[None, :] + 1) * go_stride_n
        grad_slice = tl.load(
            grad_out_ptr + offs_m[:, None] * go_stride_m + column_offsets,
            mask=mask,
            other=0.0,
        )
        path_slice = tl.load(
            out_ptr
            + offs_m[:, None] * out_stride_m
            + (offs_n[None, :] + 1) * out_stride_n,
            mask=mask,
            other=0.0,
        )

        # P = dL/dlog_path = G * S.
        p = tl.where(mask, grad_slice * path_slice, zeros_mn)
        chunk_total = tl.sum(p, axis=1)

        # Suffix sum inside the chunk, built from forward primitives:
        #     suffix[j] = total - inclusive_prefix[j] + P[j]
        suffix = chunk_total[:, None] - tl.cumsum(p, axis=1) + p
        q = tl.where(mask, suffix + carry[:, None], zeros_mn)

        tl.store(
            grad_dw_ptr
            + offs_m[:, None] * gdw_stride_m
            + offs_n[None, :] * gdw_stride_n,
            sigma * q,
            mask=mask,
        )

        dw = tl.load(
            dw_ptr + offs_m[:, None] * dw_stride_m + offs_n[None, :] * dw_stride_n,
            mask=mask,
            other=0.0,
        )

        acc_s0 = acc_s0 + chunk_total / s0
        acc_mu = acc_mu + tl.sum(q, axis=1) * dt
        acc_sigma = acc_sigma + tl.sum(q * (dw - sigma * dt), axis=1)
        carry = carry + chunk_total

    tl.store(partial_s0_ptr + pid, tl.sum(acc_s0, axis=0))
    tl.store(partial_mu_ptr + pid, tl.sum(acc_mu, axis=0))
    tl.store(partial_sigma_ptr + pid, tl.sum(acc_sigma, axis=0))


# ==========================================================================
# Pure-PyTorch reference adjoint (CPU-testable)
# ==========================================================================
def reference_gbm_backward(
    grad_out: Tensor,
    paths: Tensor,
    dW: Tensor,
    s0: Tensor,
    sigma: Tensor,
    dt: float,
) -> Tuple[Tensor, Tensor, Tensor, Tensor]:
    r"""Vectorised PyTorch implementation of the same analytic adjoint.

    This exists so the *mathematics* of the backward pass can be validated
    against ``torch.autograd`` on a CPU-only machine, independently of whether
    Triton or a GPU is available. The Triton kernel implements exactly these
    formulas; if this function agrees with autograd and the kernel agrees with
    this function, the kernel is correct.

    It is also written in ordinary differentiable PyTorch, so unlike the kernel
    it supports double backward -- making it the fallback for second-order work
    (Gamma, Hessian-vector products).

    Args:
        grad_out: Incoming adjoint :math:`G`, shape ``(n_paths, n_steps + 1)``.
        paths: Forward output :math:`S`, shape ``(n_paths, n_steps + 1)``.
        dW: Brownian increments, shape ``(n_paths, n_steps)``.
        s0: Initial spot, 0-dim tensor. Must be non-zero.
        sigma: Volatility, 0-dim tensor.
        dt: Time step.

    Returns:
        ``(grad_s0, grad_mu, grad_sigma, grad_dW)``. The three parameter
        gradients are 0-dim; ``grad_dW`` matches ``dW``'s shape.

    Raises:
        ValueError: On inconsistent shapes.
    """
    if grad_out.shape != paths.shape:
        raise ValueError(
            f"grad_out {tuple(grad_out.shape)} must match paths {tuple(paths.shape)}"
        )
    if dW.shape[0] != paths.shape[0] or dW.shape[1] != paths.shape[1] - 1:
        raise ValueError(
            f"dW {tuple(dW.shape)} inconsistent with paths {tuple(paths.shape)}"
        )

    # P[:, j] is the adjoint of log_path at time index j (output column j + 1).
    p = grad_out[:, 1:] * paths[:, 1:]

    # Q is the suffix sum of P along time: Q[:, j] = sum_{i >= j} P[:, i].
    # Implemented as flip -> cumsum -> flip, which is the readable form; the
    # kernel uses the total-minus-prefix identity instead to avoid needing a
    # reverse scan primitive.
    q = torch.flip(torch.cumsum(torch.flip(p, dims=(1,)), dim=1), dims=(1,))

    grad_dw = sigma * q
    grad_mu = q.sum() * dt
    # The -sigma*dt term is the Ito correction's contribution to Vega.
    grad_sigma = (q * (dW - sigma * dt)).sum()
    grad_s0 = grad_out[:, 0].sum() + p.sum() / s0

    return grad_s0, grad_mu, grad_sigma, grad_dw


# ==========================================================================
# autograd.Function
# ==========================================================================
class FusedGBMFunction(torch.autograd.Function):
    """Autograd wrapper binding the fused kernels into the existing AAD pipeline.

    The forward pass runs :func:`_fused_gbm_forward_kernel`; the backward pass
    runs :func:`_fused_gbm_backward_kernel` and reduces its per-program partials
    host-side. From PyTorch's perspective this is an ordinary differentiable op,
    so everything downstream -- payoffs, exposure profiles, CVA, the Phase 1-2
    Greeks machinery -- keeps working unchanged.
    """

    @staticmethod
    def forward(  # type: ignore[override]
        ctx,
        s0: Tensor,
        mu: Tensor,
        sigma: Tensor,
        dW: Tensor,
        dt: float,
    ) -> Tensor:
        """Generate paths on the GPU.

        Args:
            ctx: Autograd context.
            s0: Initial spot, 0-dim tensor on the same device/dtype as ``dW``.
            mu: Drift, 0-dim tensor.
            sigma: Volatility, 0-dim tensor.
            dW: Brownian increments of shape ``(n_paths, n_steps)`` on CUDA.
            dt: Time step.

        Returns:
            Paths of shape ``(n_paths, n_steps + 1)``.
        """
        _require_runtime()

        n_paths, n_steps = dW.shape
        out = torch.empty(
            (n_paths, n_steps + 1), device=dW.device, dtype=dW.dtype
        )

        # Pack the scalars into a device tensor. Building it with torch.stack
        # (rather than float(...)) keeps everything on-device: reading a CUDA
        # scalar into Python would force a host sync on every call, which would
        # show up directly in the Phase 3 benchmark.
        params = torch.stack(
            (
                s0.reshape(()),
                mu.reshape(()),
                sigma.reshape(()),
                torch.as_tensor(dt, device=dW.device, dtype=dW.dtype),
            )
        ).contiguous()

        block_m, block_n = select_block_sizes(n_steps, dW.element_size())
        dtype = tl.float64 if dW.dtype == torch.float64 else tl.float32
        grid = (triton.cdiv(n_paths, block_m),)

        _fused_gbm_forward_kernel[grid](
            dW,
            params,
            out,
            n_paths,
            n_steps,
            dW.stride(0),
            dW.stride(1),
            out.stride(0),
            out.stride(1),
            BLOCK_M=block_m,
            BLOCK_N=block_n,
            DTYPE=dtype,
        )

        ctx.save_for_backward(dW, out, params)
        ctx.dt = dt
        ctx.block_m = block_m
        ctx.block_n = block_n
        return out

    @staticmethod
    @torch.autograd.function.once_differentiable
    def backward(  # type: ignore[override]
        ctx, grad_out: Tensor
    ) -> Tuple[Optional[Tensor], Optional[Tensor], Optional[Tensor], Optional[Tensor], None]:
        """Run the hand-written adjoint kernel.

        Args:
            ctx: Autograd context carrying the saved forward tensors.
            grad_out: Incoming adjoint of shape ``(n_paths, n_steps + 1)``.

        Returns:
            Gradients for ``(s0, mu, sigma, dW, dt)``; ``dt`` is a
            non-differentiable Python float so its slot is ``None``, and any
            input that did not require grad also yields ``None``.
        """
        dW, out, params = ctx.saved_tensors
        n_paths, n_steps = dW.shape

        # A non-contiguous incoming adjoint would still be handled by the
        # stride arguments, but making it contiguous keeps the loads coalesced.
        grad_out = grad_out.contiguous()

        grad_dw = torch.empty_like(dW)
        block_m, block_n = ctx.block_m, ctx.block_n
        n_programs = triton.cdiv(n_paths, block_m)

        partial_s0 = torch.empty(n_programs, device=dW.device, dtype=dW.dtype)
        partial_mu = torch.empty(n_programs, device=dW.device, dtype=dW.dtype)
        partial_sigma = torch.empty(n_programs, device=dW.device, dtype=dW.dtype)

        dtype = tl.float64 if dW.dtype == torch.float64 else tl.float32

        _fused_gbm_backward_kernel[(n_programs,)](
            grad_out,
            out,
            dW,
            params,
            grad_dw,
            partial_s0,
            partial_mu,
            partial_sigma,
            n_paths,
            n_steps,
            grad_out.stride(0),
            grad_out.stride(1),
            out.stride(0),
            out.stride(1),
            dW.stride(0),
            dW.stride(1),
            grad_dw.stride(0),
            grad_dw.stride(1),
            BLOCK_M=block_m,
            BLOCK_N=block_n,
            DTYPE=dtype,
        )

        needs_s0, needs_mu, needs_sigma, needs_dw, _ = ctx.needs_input_grad
        return (
            partial_s0.sum() if needs_s0 else None,
            partial_mu.sum() if needs_mu else None,
            partial_sigma.sum() if needs_sigma else None,
            grad_dw if needs_dw else None,
            None,
        )


