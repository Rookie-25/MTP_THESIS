def _as_param(value, device: torch.device, dtype: torch.dtype, name: str) -> Tensor:
    """Coerce a scalar-like parameter to a 0-dim tensor, preserving grad.

    Mirrors ``src.models.gbm._as_param`` so the two simulators accept exactly
    the same inputs.

    Args:
        value: Python float or scalar tensor.
        device: Target device.
        dtype: Target dtype.
        name: Parameter name for error messages.

    Returns:
        A 0-dim tensor on ``device`` with dtype ``dtype``.

    Raises:
        ValueError: If ``value`` is a tensor with more than one element.
    """
    if isinstance(value, Tensor):
        if value.numel() != 1:
            raise ValueError(
                f"model parameter {name!r} must be scalar, got shape {tuple(value.shape)}"
            )
        tensor = value.to(device=device, dtype=dtype)
        return tensor if tensor.ndim == 0 else tensor.reshape(())
    return torch.as_tensor(float(value), device=device, dtype=dtype)


def triton_simulate_gbm(s0, mu, sigma, dW: Tensor, dt: float) -> Tensor:
    r"""Fused GPU GBM simulation, API-compatible with :func:`src.models.gbm.simulate_gbm`.

    Drop-in replacement: identical signature, identical output shape and
    semantics, identical gradient behaviour. The only differences are that
    ``dW`` must live on a CUDA device and that second-order differentiation is
    unsupported (see the module docstring).

    Args:
        s0: Initial spot :math:`S_0`. Pass a tensor with ``requires_grad=True``
            to obtain Delta.
        mu: Drift :math:`\mu`. Equal to the risk-free rate under
            :math:`\mathbb{Q}`.
        sigma: Volatility :math:`\sigma`. Pass a tensor with
            ``requires_grad=True`` to obtain Vega.
        dW: Brownian increments of shape ``(n_paths, n_steps)`` on CUDA. Its
            device and dtype define those of the output.
        dt: Step size :math:`\Delta t` used to generate ``dW``.

    Returns:
        Paths of shape ``(n_paths, n_steps + 1)``. Column ``0`` is
        :math:`S_0` on every path; column ``k`` is :math:`S_{k\Delta t}`.

    Raises:
        RuntimeError: If Triton or CUDA is unavailable.
        ValueError: If ``dW`` is not a 2-D CUDA tensor, is empty, or ``dt`` is
            non-positive.

    Example:
        >>> dW = torch.randn(1024, 252, device="cuda", dtype=torch.float32)
        >>> s0 = torch.tensor(100.0, device="cuda", requires_grad=True)
        >>> paths = triton_simulate_gbm(s0, 0.03, 0.2, dW, 1.0 / 252)
        >>> paths.shape
        torch.Size([1024, 253])
    """
    _require_runtime()

    if not isinstance(dW, Tensor):
        raise ValueError(f"dW must be a torch.Tensor, got {type(dW).__name__}")
    if dW.ndim != 2:
        raise ValueError(
            f"dW must be 2-dimensional (n_paths, n_steps), got {tuple(dW.shape)}"
        )
    if dW.numel() == 0:
        raise ValueError("dW must be non-empty")
    if not dW.is_cuda:
        raise ValueError(
            "the fused kernel is GPU-only; dW must be a CUDA tensor "
            "(use src.models.gbm.simulate_gbm for CPU)"
        )
    if dW.dtype not in (torch.float32, torch.float64):
        raise ValueError(
            f"dW must be float32 or float64, got {dW.dtype}"
        )
    if not isinstance(dt, (int, float)) or isinstance(dt, bool):
        raise ValueError(f"dt must be a real number, got {type(dt).__name__}")
    if not math.isfinite(float(dt)) or float(dt) <= 0.0:
        raise ValueError(f"dt must be positive and finite, got {dt}")

    device, dtype = dW.device, dW.dtype
    s0_t = _as_param(s0, device, dtype, "s0")
    mu_t = _as_param(mu, device, dtype, "mu")
    sigma_t = _as_param(sigma, device, dtype, "sigma")

    return FusedGBMFunction.apply(s0_t, mu_t, sigma_t, dW, float(dt))
