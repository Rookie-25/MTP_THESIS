r"""Fused Triton GBM path generator with a hand-written adjoint.

Why this kernel exists
======================
The pure-PyTorch simulator in :mod:`src.models.gbm` is correct and fully
differentiable, but it is **global-memory-bandwidth bound**. A single call to
``simulate_gbm`` materialises roughly five :math:`M \times N` tensors in HBM:

===========================  ==============================================
tensor                       produced by
===========================  ==============================================
``sigma * dW``               elementwise multiply
``drift + sigma * dW``       elementwise add
``cumsum(...)``              scan
``cat(zeros, ...)``          concatenation to width :math:`N+1`
``s0 * exp(...)``            exponential + scale
===========================  ==============================================

Every one of those is a full round trip to device memory for what is
arithmetically a handful of FLOPs per element. The kernel below performs the
entire chain -- increment scaling, the running cumulative sum along time, the
exponential, and the :math:`S_0` scale -- inside registers and SRAM, reading
``dW`` **once** and writing the path matrix **once**.

The scan strategy
=================
The cumulative sum runs along *time*, while paths are mutually independent. So
each Triton program owns a tile of ``BLOCK_M`` paths and walks the whole time
axis itself, carrying a running offset between chunks of ``BLOCK_N`` steps:

.. code-block:: text

    carry = 0
    for each chunk of BLOCK_N time steps:
        incr      = drift + sigma * dW[chunk]          # in registers
        log_path  = cumsum(incr, axis=time) + carry    # in SRAM
        S[chunk]  = s0 * exp(log_path)                 # single store
        carry    += sum(incr, axis=time)

Chunking (rather than one giant ``BLOCK_N >= N`` tile) keeps SRAM pressure
bounded and makes the kernel work for any :math:`N`, not just small ones.

The adjoint -- derived, not autogenerated
=========================================
Triton kernels are opaque to PyTorch's autograd, so the backward pass must be
written by hand. Getting it exactly right is non-negotiable: the whole Phase 1-2
pipeline (Greeks, CVA sensitivities) hangs off these gradients.

With :math:`a = (\mu - \tfrac12\sigma^2)\Delta t` and
:math:`\iota_{m,j} = a + \sigma\,\Delta W_{m,j}`, the forward map is

.. math::
    L_{m,k} = \sum_{j=1}^{k} \iota_{m,j},
    \qquad S_{m,k} = S_0 e^{L_{m,k}},
    \qquad S_{m,0} = S_0 .

Let :math:`G_{m,k} = \partial\mathcal{L}/\partial S_{m,k}` be the incoming
adjoint. Then

.. math::
    \frac{\partial \mathcal{L}}{\partial L_{m,k}}
        = G_{m,k}\, S_0 e^{L_{m,k}} = G_{m,k} S_{m,k} \;=:\; P_{m,k},

and because :math:`L_{m,k}` accumulates *every* increment up to :math:`k`, the
adjoint of a single increment is a **suffix sum** of :math:`P`:

.. math::
    Q_{m,j} \;=\; \frac{\partial\mathcal{L}}{\partial \iota_{m,j}}
        \;=\; \sum_{k \ge j} P_{m,k}.

The three parameter gradients then follow by the chain rule through
:math:`\iota`:

.. math::
    \frac{\partial\mathcal{L}}{\partial S_0}
        &= \sum_{m,k} G_{m,k}\, e^{L_{m,k}}
         = \sum_m G_{m,0} + \frac{1}{S_0}\sum_{m,k\ge1} P_{m,k}, \\
    \frac{\partial\mathcal{L}}{\partial \mu}
        &= \Delta t \sum_{m,j} Q_{m,j}, \\
    \frac{\partial\mathcal{L}}{\partial \sigma}
        &= \sum_{m,j} Q_{m,j}\left(\Delta W_{m,j} - \sigma\,\Delta t\right), \\
    \frac{\partial\mathcal{L}}{\partial \Delta W_{m,j}}
        &= \sigma\, Q_{m,j}.

The :math:`-\sigma\Delta t` term in the Vega is the Ito correction's
contribution and is the single easiest thing to drop by accident; omitting it
produces a Vega that looks plausible and is wrong by
:math:`\sigma\Delta t\sum Q`.

Computing the suffix sum without a reverse scan
-----------------------------------------------
Rather than flipping tensors (which not every Triton version exposes), the
backward walks chunks **from the last to the first** and uses the identity

.. math::
    \underbrace{\sum_{i=j}^{hi-1} P_i}_{\text{suffix within chunk}}
    = \underbrace{\sum_{i=lo}^{hi-1} P_i}_{\text{chunk total}}
    - \underbrace{\sum_{i=lo}^{j} P_i}_{\text{inclusive prefix}}
    + P_j ,

so only forward ``cumsum`` and ``sum`` primitives are needed.

Determinism
-----------
The scalar gradients are reduced via **per-program partial buffers summed in
PyTorch**, not ``tl.atomic_add``. Atomics would make the result depend on
program completion order, so two identical runs could differ in the last bits --
unacceptable for a thesis benchmark, and a nightmare to debug against a
finite-difference oracle. The partial-buffer reduction is bitwise reproducible
and sidesteps the patchy float64 atomic support in Triton.

Known limitation: no double backward
====================================
:meth:`FusedGBMFunction.backward` is marked ``once_differentiable``. The kernel
path therefore supports first-order sensitivities only -- attempting to
differentiate the gradient (for Gamma, or a Hessian-vector product) raises a
clear error rather than returning silent garbage. The pure-PyTorch path in
:mod:`src.models.gbm` *does* support double backward, and
:func:`reference_gbm_backward` below is itself written in differentiable
PyTorch, so second-order work has a validated fallback. Making the Triton
adjoint itself differentiable would mean writing a second-order kernel; that is
deliberately out of Phase 3 scope.

Future work
-----------
``dW`` is still materialised in HBM by the caller. Folding a counter-based
(Philox) RNG into the kernel would remove that :math:`M \times N` allocation
entirely and make peak memory :math:`O(M)` rather than :math:`O(MN)`. That is
the natural next optimisation once this kernel is validated.
"""

