def is_available() -> bool:
    """Report whether the fused kernels can actually run here.

    Returns:
        ``True`` only when Triton is importable *and* a CUDA device is visible.
    """
    return HAS_TRITON and torch.cuda.is_available()


def _require_runtime() -> None:
    """Raise a precise error when the fused path cannot run.

    Raises:
        RuntimeError: If Triton is missing or no CUDA device is present.
    """
    if not HAS_TRITON:
        raise RuntimeError(
            "Triton is not installed. The fused GBM kernel requires Triton and a "
            "CUDA device; use src.models.gbm.simulate_gbm for the portable path."
        )
    if not torch.cuda.is_available():
        raise RuntimeError(
            "No CUDA device is visible to PyTorch. The fused GBM kernel is "
            "GPU-only; use src.models.gbm.simulate_gbm on CPU."
        )


# ==========================================================================
# Block-size selection
# ==========================================================================
def select_block_sizes(n_steps: int, element_size: int) -> Tuple[int, int]:
    """Choose ``(BLOCK_M, BLOCK_N)`` for a given time-axis length and dtype.

    ``BLOCK_N`` is the time-chunk width and must be a power of two because
    Triton's ``cumsum`` operates on power-of-two tiles. ``BLOCK_M`` is then
    chosen so the working tile stays inside a modest SRAM budget, leaving room
    for several concurrent programs per streaming multiprocessor.

    Args:
        n_steps: Number of time steps :math:`N`.
        element_size: Bytes per element (``4`` for float32, ``8`` for float64).

    Returns:
        ``(BLOCK_M, BLOCK_N)``, both powers of two.

    Raises:
        ValueError: If ``n_steps`` or ``element_size`` is non-positive.
    """
    if n_steps <= 0:
        raise ValueError(f"n_steps must be positive, got {n_steps}")
    if element_size <= 0:
        raise ValueError(f"element_size must be positive, got {element_size}")

    # Next power of two at or above n_steps, capped so a long horizon is walked
    # in several chunks rather than one oversized tile.
    block_n = 1 << max(0, (n_steps - 1).bit_length())
    block_n = max(16, min(block_n, 128))

    # ~32 KiB per tile keeps occupancy healthy on every CUDA architecture we
    # care about, without querying device properties at import time.
    tile_budget_bytes = 32 * 1024
    block_m = tile_budget_bytes // (block_n * element_size)
    block_m = max(1, min(64, block_m))
    block_m = 1 << (block_m.bit_length() - 1)  # round down to a power of two

    return block_m, block_n


